"""
make_planted_bugs.py: write copies of jobs_pyspark/sale.py, each with exactly one planted bug.

Each bug is a realistic mistake an AI translator could make. We then run every copy through
run_spark.py and check.py on the dev and holdout data, to see whether the checker catches it
("mutation testing": testing the tester). Run scripts/run_planted_bugs.py for that.

Each bug is a find-and-replace on the real translation. If sale.py changes and a find string
no longer appears exactly once, this script stops instead of writing a wrong copy.

Usage (from the repo root):
    python scripts/make_planted_bugs.py
"""
from pathlib import Path

SOURCE = Path("jobs_pyspark/sale.py")
OUT = Path("experiments/planted_bugs")

BUGS = [
    ("no_valid_to", "Dimension lookups forget the [Valid To] condition",
     '            & (F.col("Last Modified When") <= F.col("__d_to"))\n', ""),
    ("ge_valid_from", "Dimension lookups use >= instead of > on [Valid From]",
     '(F.col("Last Modified When") > F.col("__d_from"))',
     '(F.col("Last Modified When") >= F.col("__d_from"))'),
    ("null_not_zero", "No matching dimension row gives NULL instead of 0 (COALESCE dropped)",
     'F.coalesce(F.col("__d_key").cast("long"), F.lit(0).cast("long"))',
     'F.col("__d_key").cast("long")'),
    ("top1_desc", "TOP(1) ... ORDER BY [Valid From] taken in the wrong order (newest first)",
     'F.col("__d_from").asc_nulls_first(), F.col("__d_key").asc_nulls_first()',
     'F.col("__d_from").desc_nulls_last(), F.col("__d_key").asc_nulls_first()'),
    ("no_delete", "Old lines of reloaded invoices are not deleted before the new ones are inserted",
     "new_fact = kept.select(", "new_fact = fact_sale.select("),
    ("changed_rows_only", "Fact.Sale returns only the inserted rows, not the whole table",
     "new_fact = kept.select(*[F.col(c) for c in fact_cols]).unionByName(inserted)",
     "new_fact = inserted"),
    ("default_decimal", "Money columns cast with Spark's default decimal(10,0), losing the cents",
     "        return expr.cast(fact_types[name]).alias(name)",
     "        t = fact_types[name]\n"
     "        return expr.cast(\"decimal\" if t.typeName() == \"decimal\" else t).alias(name)"),
    ("tax_rate_scale", "Tax Rate written as decimal(18,2) instead of decimal(18,3)",
     '        elif c == "Lineage Key":',
     '        elif c == "Tax Rate":\n'
     '            insert_exprs.append(F.col(c).cast("decimal(18,2)").alias(c))\n'
     '        elif c == "Lineage Key":'),
    ("forget_cutoff", "The Integration.[ETL Cutoff] update is left out",
     '        "Integration.ETL Cutoff": new_cutoff,\n', ""),
]


def main():
    source = SOURCE.read_text()
    OUT.mkdir(parents=True, exist_ok=True)
    for name, what, find, replace in BUGS:
        if source.count(find) != 1:
            raise SystemExit(f"{name}: expected the find string once in {SOURCE}, found {source.count(find)}")
        header = (f'"""PLANTED BUG ({name}): {what}.\n'
                  f"Generated by scripts/make_planted_bugs.py from {SOURCE}. Not a real translation.\n"
                  '"""\n')
        (OUT / f"{name}.py").write_text(header + source.replace(find, replace))
        print(f"   wrote {OUT / name}.py  ({what})")


if __name__ == "__main__":
    main()
